/**
 * Writes src/data/brandIcons.ts from simple-icons.
 *
 * The marks are baked into a source file rather than imported at runtime so
 * the 3,000-icon package stays a build-time dependency and never reaches the
 * bundle. Re-run with `node scripts/gen-brand-icons.mjs` after changing the
 * list below.
 *
 * Some brands are absent from simple-icons because their owners asked to be
 * removed. Those are rendered as wordmark tiles in the skills data instead.
 */

import { writeFileSync } from "node:fs";
import * as icons from "simple-icons";

const WANTED = [
  "nodedotjs", "python", "django", "typescript", "postgresql", "redis", "celery", "docker",
  "react", "nextdotjs", "tailwindcss", "javascript", "html5", "sass", "threedotjs", "reactquery",
  "dart", "expo",
  "claude", "googlegemini", "n8n", "langchain", "langgraph", "huggingface", "ollama",
  "qdrant", "whatsapp", "firebase",
  "odoo", "figma", "jira", "notion", "github",
  "flutter", "android",
  "googlecloud", "supabase", "airtable", "vercel",
];

const key = (slug) => "si" + slug.charAt(0).toUpperCase() + slug.slice(1);

const missing = WANTED.filter((slug) => !icons[key(slug)]);
if (missing.length) {
  console.error("Not in simple-icons: " + missing.join(", "));
  process.exit(1);
}

const entries = WANTED.map((slug) => {
  const icon = icons[key(slug)];
  return `  ${slug}: {\n    title: ${JSON.stringify(icon.title)},\n    hex: "#${icon.hex}",\n    path: ${JSON.stringify(icon.path)},\n  },`;
}).join("\n");

const file = `/**
 * Brand marks, generated by scripts/gen-brand-icons.mjs from simple-icons.
 * Do not edit by hand: change the list in that script and re-run it.
 *
 * Each path is drawn in a 24x24 viewBox. Brand names and logos are
 * trademarks of their respective owners; they appear here to identify the
 * technologies used, which does not imply any endorsement.
 */

export interface BrandIcon {
  title: string;
  hex: string;
  path: string;
}

export const brandIcons = {
${entries}
} as const satisfies Record<string, BrandIcon>;

export type BrandKey = keyof typeof brandIcons;
`;

writeFileSync(new URL("../src/data/brandIcons.ts", import.meta.url), file, "utf8");
console.log(`wrote ${WANTED.length} brand marks to src/data/brandIcons.ts`);
